import { useState } from 'react';
import {
  View,
  Text,
  StyleSheet,
  TouchableOpacity,
  KeyboardAvoidingView,
  ScrollView,
  Platform,
  Image,
} from 'react-native';
import { router } from 'expo-router';
import { LinearGradient } from 'expo-linear-gradient';
import { BlurView } from 'expo-blur';
import { Ionicons } from '@expo/vector-icons';
import Animated, { FadeIn, FadeInDown } from 'react-native-reanimated';
import * as Haptics from 'expo-haptics';
import { supabase } from '@/lib/supabase';
import { useAuth } from '@/contexts/AuthContext';
import { Colors, Gradients } from '@/constants/colors';
import Input from '@/components/ui/Input';
import Button from '@/components/ui/Button';

export default function OnboardingCreateTeamScreen() {
  const { user } = useAuth();
  const [teamName, setTeamName] = useState('');
  const [teamNameError, setTeamNameError] = useState('');
  const [loading, setLoading] = useState(false);
  const [generalError, setGeneralError] = useState('');

  const validate = () => {
    if (!teamName.trim()) {
      setTeamNameError('Team name is required');
      return false;
    }
    if (teamName.trim().length < 2) {
      setTeamNameError('Team name must be at least 2 characters');
      return false;
    }
    setTeamNameError('');
    return true;
  };

  const handleCreate = async () => {
    if (!validate()) return;

    setLoading(true);
    setGeneralError('');

    try {
      // Create the team (invite_code auto-generated by DB trigger)
      const { data: team, error: teamError } = await supabase
        .from('teams')
        .insert({
          name: teamName.trim(),
          created_by: user!.id,
        })
        .select('id, invite_code')
        .single();

      if (teamError) throw teamError;

      // Add creator as head coach
      const { error: coachError } = await supabase
        .from('team_coaches')
        .insert({
          team_id: team.id,
          coach_id: user!.id,
          role: 'head_coach',
        });

      if (coachError) throw coachError;

      Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success);

      // Navigate to invite code screen (replace so back doesn't loop)
      router.replace({
        pathname: '/(onboarding)/invite-code',
        params: { inviteCode: team.invite_code, teamName: teamName.trim() },
      });
    } catch (error) {
      setGeneralError(
        error instanceof Error ? error.message : 'Failed to create team. Please try again.'
      );
      Haptics.notificationAsync(Haptics.NotificationFeedbackType.Error);
    } finally {
      setLoading(false);
    }
  };

  return (
    <LinearGradient
      colors={Gradients.primary as unknown as string[]}
      style={styles.gradient}
      start={{ x: 0.1, y: 0 }}
      end={{ x: 0.9, y: 1 }}
    >
      <View style={styles.decorCircle1} />
      <View style={styles.decorCircle2} />

      <KeyboardAvoidingView
        behavior={Platform.OS === 'ios' ? 'padding' : 'height'}
        style={styles.keyboardView}
      >
        <ScrollView
          contentContainerStyle={styles.scrollContent}
          keyboardShouldPersistTaps="handled"
          showsVerticalScrollIndicator={false}
        >
          {/* Back button */}
          <Animated.View entering={FadeIn.duration(400)} style={styles.backRow}>
            <TouchableOpacity
              style={styles.backButton}
              onPress={() => router.back()}
              activeOpacity={0.8}
            >
              <Ionicons name="arrow-back" size={20} color="rgba(255,255,255,0.9)" />
            </TouchableOpacity>
          </Animated.View>

          {/* Header with icon */}
          <Animated.View entering={FadeInDown.delay(100).springify()} style={styles.headerSection}>
            <LinearGradient
              colors={['rgba(255,255,255,0.2)', 'rgba(255,255,255,0.1)']}
              style={styles.teamIconCircle}
            >
              <Ionicons name="shield-checkmark" size={32} color="#fff" />
            </LinearGradient>
            <Text style={styles.title}>Create Your Team</Text>
            <Text style={styles.subtitle}>
              Give your team a name to get started. You'll get a player invite code next.
            </Text>
          </Animated.View>

          {/* Form card */}
          <Animated.View entering={FadeInDown.delay(200).springify()} style={styles.cardContainer}>
            <BlurView intensity={40} tint="light" style={styles.blurContainer}>
              <View style={styles.card}>
                {/* MatchFit Icon inside card */}
                <View style={styles.cardIconRow}>
                  <Image
                    source={require('../../assets/logo-icon.png')}
                    style={styles.cardIconImg}
                    resizeMode="contain"
                  />
                </View>

                {/* General error */}
                {generalError ? (
                  <View style={styles.errorBanner}>
                    <Ionicons name="alert-circle-outline" size={16} color={Colors.error} />
                    <Text style={styles.errorBannerText}>{generalError}</Text>
                  </View>
                ) : null}

                <Input
                  label="Team Name"
                  icon="shield-outline"
                  value={teamName}
                  onChangeText={(text) => {
                    setTeamName(text);
                    if (teamNameError) setTeamNameError('');
                    if (generalError) setGeneralError('');
                  }}
                  error={teamNameError}
                  editable={!loading}
                  containerStyle={styles.inputContainer}
                  autoFocus
                  autoCapitalize="words"
                  returnKeyType="done"
                  onSubmitEditing={handleCreate}
                />

                <Button
                  title="Create Team"
                  onPress={handleCreate}
                  loading={loading}
                  disabled={loading}
                  style={styles.createButton}
                />
              </View>
            </BlurView>
          </Animated.View>

          {/* Step indicator */}
          <Animated.View entering={FadeInDown.delay(300).springify()} style={styles.stepIndicator}>
            <View style={styles.stepDot} />
            <View style={[styles.stepDot, styles.stepDotActive]} />
            <View style={styles.stepDot} />
          </Animated.View>
        </ScrollView>
      </KeyboardAvoidingView>
    </LinearGradient>
  );
}

