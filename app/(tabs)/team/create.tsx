import { useState } from 'react';
import {
  View,
  Text,
  StyleSheet,
  TouchableOpacity,
  Alert,
  Share,
  Platform,
  KeyboardAvoidingView,
  ScrollView,
} from 'react-native';
import { router } from 'expo-router';
import Animated, { FadeInDown, FadeIn } from '@/utils/reanimated-shim';
import { LinearGradient } from 'expo-linear-gradient';
import { Ionicons } from '@expo/vector-icons';
import * as Haptics from 'expo-haptics';
import { supabase } from '@/lib/supabase';
import { useAuth } from '@/contexts/AuthContext';
import { Colors, Gradients } from '@/constants/colors';
import Input from '@/components/ui/Input';
import Button from '@/components/ui/Button';

export default function CreateTeamScreen() {
  const { user } = useAuth();
  const [teamName, setTeamName] = useState('');
  const [teamNameError, setTeamNameError] = useState('');
  const [loading, setLoading] = useState(false);
  const [inviteCode, setInviteCode] = useState<string | null>(null);

  const validate = () => {
    if (!teamName.trim()) {
      setTeamNameError('Team name is required');
      return false;
    }
    if (teamName.trim().length < 2) {
      setTeamNameError('Team name must be at least 2 characters');
      return false;
    }
    setTeamNameError('');
    return true;
  };

  const handleCreate = async () => {
    if (!validate()) return;

    setLoading(true);
    try {
      // Insert team (invite_code is auto-generated by DB trigger)
      const { data: team, error: teamError } = await supabase
        .from('teams')
        .insert({
          name: teamName.trim(),
          created_by: user!.id,
        })
        .select('id, invite_code')
        .single();

      if (teamError) throw teamError;

      // Insert creator as head coach
      const { error: coachError } = await supabase
        .from('team_coaches')
        .insert({
          team_id: team.id,
          coach_id: user!.id,
          role: 'head_coach',
        });

      if (coachError) throw coachError;

      Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success);
      setInviteCode(team.invite_code);
    } catch (error) {
      Alert.alert(
        'Error',
        error instanceof Error ? error.message : 'Failed to create team'
      );
    } finally {
      setLoading(false);
    }
  };

  const handleShare = async () => {
    if (!inviteCode) return;
    try {
      await Share.share({
        message: `Join my team on MatchFit! Use invite code: ${inviteCode}`,
      });
    } catch {
      // User dismissed share sheet
    }
  };

  // ── Success State ─────────────────────────────────────────
  if (inviteCode) {
    return (
      <View style={styles.container}>
        <View style={styles.handle} />

        <Animated.View entering={FadeIn.duration(400)} style={styles.successContainer}>
          {/* Success icon */}
          <View style={styles.successIconWrapper}>
            <LinearGradient
              colors={Gradients.success as unknown as string[]}
              style={styles.successIconGradient}
            >
              <Ionicons name="checkmark" size={44} color="#fff" />
            </LinearGradient>
          </View>

          <Text style={styles.successTitle}>Team Created!</Text>
          <Text style={styles.successSubtitle}>
            Share this code with your players so they can join
          </Text>

          {/* Invite Code Card - Tappable to Share */}
          <Animated.View entering={FadeInDown.delay(150).springify()}>
            <TouchableOpacity onPress={handleShare} activeOpacity={0.8}>
              <View style={styles.codeCard}>
                <Text style={styles.codeLabel}>INVITE CODE</Text>
                <Text style={styles.codeText}>{inviteCode}</Text>
                <Text style={styles.codeTapHint}>Tap to share</Text>
              </View>
            </TouchableOpacity>
          </Animated.View>

          {/* Share Button */}
          <Animated.View entering={FadeInDown.delay(250).springify()} style={styles.shareButtonContainer}>
            <TouchableOpacity
              style={styles.shareButton}
              onPress={handleShare}
              activeOpacity={0.85}
            >
              <Ionicons name="share-social-outline" size={20} color="#fff" />
              <Text style={styles.shareButtonText}>Share Code</Text>
            </TouchableOpacity>
          </Animated.View>

          {/* Done */}
          <Animated.View entering={FadeInDown.delay(350).springify()} style={styles.doneContainer}>
            <Button title="Done" onPress={() => router.back()} />
          </Animated.View>
        </Animated.View>
      </View>
    );
  }

  // ── Form State ────────────────────────────────────────────
  return (
    <KeyboardAvoidingView
      behavior={Platform.OS === 'ios' ? 'padding' : 'height'}
      style={styles.container}
    >
      <ScrollView
        contentContainerStyle={styles.scrollContent}
        keyboardShouldPersistTaps="handled"
        showsVerticalScrollIndicator={false}
      >
        {/* Bottom-sheet handle */}
        <View style={styles.handle} />

        {/* Header row */}
        <Animated.View entering={FadeIn.duration(400)} style={styles.header}>
          <TouchableOpacity style={styles.closeButton} onPress={() => router.back()}>
            <Ionicons name="close" size={20} color={Colors.textSecondary} />
          </TouchableOpacity>
          <Text style={styles.headerTitle}>Create Team</Text>
          <View style={styles.headerSpacer} />
        </Animated.View>

        {/* Icon + subtitle */}
        <Animated.View entering={FadeIn.delay(100).duration(600)} style={styles.iconSection}>
          <LinearGradient
            colors={Gradients.primary as unknown as string[]}
            style={styles.teamIcon}
          >
            <Ionicons name="people" size={36} color="#fff" />
          </LinearGradient>
          <Text style={styles.subtitle}>Give your team a name to get started</Text>
        </Animated.View>

        {/* Team Name Input */}
        <Animated.View entering={FadeInDown.delay(200).springify()}>
          <Input
            label="Team Name"
            icon="shield-outline"
            value={teamName}
            onChangeText={(text) => {
              setTeamName(text);
              if (teamNameError) validate();
            }}
            error={teamNameError}
            editable={!loading}
            containerStyle={styles.inputContainer}
            autoFocus
          />
        </Animated.View>

        {/* Create Button */}
        <Animated.View entering={FadeInDown.delay(300).springify()}>
          <Button
            title="Create Team"
            onPress={handleCreate}
            loading={loading}
            disabled={loading}
            style={styles.createButton}
          />
        </Animated.View>
      </ScrollView>
    </KeyboardAvoidingView>
  );
}

